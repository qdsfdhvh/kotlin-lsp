//! Real-world-style search quality battery.
//!
//! Methodology from codegraph's `SEARCH_QUALITY_LOOP.md`: a fixed corpus of
//! real-world-shaped Kotlin (OkHttp/Okio-style networking + a protobuf stub +
//! a UI screen) and a fixed query battery asserting top-N hits. The corpus is
//! parsed through the real `parse_by_extension` path and indexed with the same
//! `doc_tokens`/`TfIdfIndex`/`parse_query` code `run_search` uses, so these
//! tests guard P1 (segmentation), P2 (filters), P3 (phantom suppression keeps
//! the corpus parse clean) and P4 (generated down-ranking) together.

use super::{doc_passes_filters, doc_tokens, language_from_path, parse_query, TfIdfIndex};
use crate::indexer::detect_generated;
use crate::parser::parse_by_extension;

/// Corpus entries are parsed as standalone files; `path` feeds the
/// generated-detection signal and the language filter.
struct CorpusEntry {
    path: &'static str,
    src: &'static str,
}

fn corpus() -> Vec<CorpusEntry> {
    vec![
        // OkHttp-style networking (hand-written).
        CorpusEntry {
            path: "okhttp/src/main/kotlin/okhttp3/Request.kt",
            src: r#"
package okhttp3

/**
 * An immutable HTTP request.
 */
class Request {
    fun newBuilder(): Builder = Builder()
}

class Builder {
    fun url(url: String): Builder = this
    fun build(): Request = Request()
}
"#,
        },
        // Okio-style buffered source (hand-written, KDoc-heavy).
        CorpusEntry {
            path: "okio/src/main/kotlin/okio/Buffer.kt",
            src: r#"
package okio

/**
 * A sink that buffers written bytes in memory, ready to be read as a source.
 */
class Buffer {
    fun writeUtf8(string: String): Buffer = this
    fun readUtf8(): String = ""
}
"#,
        },
        // Protobuf-generated stub with the same class name as a real one.
        CorpusEntry {
            path: "proto/Request.pb.kt",
            src: r#"
// Code generated by the protocol buffer compiler. DO NOT EDIT!
package okhttp3

class Request {
    fun parseFrom(bytes: ByteArray): Request = this
}
"#,
        },
        // Acronym-run class names (P1 segmentation).
        CorpusEntry {
            path: "html/src/main/kotlin/com/example/HTMLParser.kt",
            src: r#"
package com.example

class HTMLParser {
    fun parse(html: String): String = html
}
"#,
        },
        CorpusEntry {
            path: "json/src/main/kotlin/com/example/JSONParser.kt",
            src: r#"
package com.example

class JSONParser {
    fun parse(json: String): String = json
}
"#,
        },
        // Digits glued to a word (P1).
        CorpusEntry {
            path: "codec/src/main/kotlin/com/example/Base64Encoder.kt",
            src: r#"
package com.example

class Base64Encoder {
    fun encode(bytes: ByteArray): String = ""
}
"#,
        },
        // UI screen with camelCase method.
        CorpusEntry {
            path: "app/src/main/kotlin/com/example/LoginViewModel.kt",
            src: r#"
package com.example

class LoginViewModel {
    fun onLoginClicked() {}
}
"#,
        },
    ]
}

/// Build the same index `run_search` would, from parsed corpus files.
fn build_corpus_index() -> (TfIdfIndex, Vec<(String, String)>) {
    let mut tfidf = TfIdfIndex::new();
    // (name, kind) per doc, in index order — for top-N assertions.
    let mut names: Vec<(String, String)> = Vec::new();
    for entry in corpus() {
        let data = parse_by_extension(entry.path, entry.src);
        assert!(
            data.syntax_errors.is_empty(),
            "corpus file {} must parse clean (P3 phantom regression): {:?}",
            entry.path,
            data.syntax_errors
        );
        let generated = detect_generated(entry.path, entry.src);
        for sym in &data.symbols {
            let tokens = doc_tokens(sym);
            let doc = super::SearchDoc {
                name: sym.name.clone(),
                kind: sym.kind_label(),
                file: entry.path.to_string(),
                line: sym.selection_start() + 1,
                signature: sym.detail.clone(),
                doc: sym.documentation.clone(),
                tokens: tokens.clone(),
                generated,
            };
            names.push((sym.name.clone(), sym.kind_label()));
            let id = tfidf.docs.len();
            tfidf.docs.push(doc);
            tfidf.add(id, &tokens);
        }
    }
    tfidf.finalize();
    (tfidf, names)
}

/// Rebuild the index with only the docs that pass `parsed`'s filters —
/// run_search filters at build time, so scoring happens inside the narrowed
/// set (codegraph: filters narrow, FTS scores within).
fn filtered_index(tfidf: &TfIdfIndex, parsed: &super::ParsedQuery) -> TfIdfIndex {
    let mut out = TfIdfIndex::new();
    for doc in &tfidf.docs {
        if !doc_passes_filters(doc, parsed, language_from_path(&doc.file)) {
            continue;
        }
        let tokens = doc.tokens.clone();
        let id = out.docs.len();
        out.docs.push(doc.clone());
        out.add(id, &tokens);
    }
    out.finalize();
    out
}

/// Query the way `run_search` does: filters parsed out, remaining text
/// expanded (stem + identifier segments at original casing), scored.
fn corpus_query(tfidf: &TfIdfIndex, raw: &str, limit: usize) -> Vec<super::SearchResult> {
    let parsed = parse_query(raw);
    let tfidf = filtered_index(tfidf, &parsed);
    let query_tokens: Vec<String> = super::tokenize_query(&parsed.text)
        .into_iter()
        .map(|t| super::stem(&t))
        .collect();
    let mut all_query_tokens = query_tokens.clone();
    for qt in &query_tokens {
        for s in super::tokenize_identifier(qt) {
            if !all_query_tokens.contains(&s) {
                all_query_tokens.push(s);
            }
        }
    }
    for seg in super::query_segments(&parsed.text) {
        if !all_query_tokens.contains(&seg) {
            all_query_tokens.push(seg);
        }
    }
    if all_query_tokens.is_empty() {
        // Filters-only query: return everything that passes, ordered by name
        // (same as run_search).
        let mut docs: Vec<&super::SearchDoc> = tfidf.docs.iter().collect();
        docs.sort_by(|a, b| {
            a.name
                .cmp(&b.name)
                .then_with(|| a.generated.cmp(&b.generated))
        });
        docs.truncate(limit);
        return docs
            .into_iter()
            .map(|d| super::SearchResult {
                name: d.name.clone(),
                kind: d.kind.clone(),
                file: d.file.clone(),
                line: d.line,
                signature: d.signature.clone(),
                doc: d.doc.clone(),
                generated: d.generated,
                score: 1.0,
            })
            .collect();
    }
    tfidf.search(&all_query_tokens, limit)
}

