#[test]
fn corpus_parses_clean() {
    // P3 guard: no phantom errors on any corpus file.
    for entry in corpus() {
        let data = parse_by_extension(entry.path, entry.src);
        assert!(
            data.syntax_errors.is_empty(),
            "{}: {:?}",
            entry.path,
            data.syntax_errors
        );
    }
}

#[test]
fn battery_acronym_names_top_hit() {
    let (tfidf, _) = build_corpus_index();
    // P1: acronym-run names match when typed as-is.
    let r = corpus_query(&tfidf, "HTMLParser", 3);
    assert_eq!(r.first().map(|x| x.name.as_str()), Some("HTMLParser"));
    let r = corpus_query(&tfidf, "JSONParser", 3);
    assert_eq!(r.first().map(|x| x.name.as_str()), Some("JSONParser"));
    // Digits glue: querying the words still finds the encoder.
    let r = corpus_query(&tfidf, "base64 encode", 3);
    assert_eq!(r.first().map(|x| x.name.as_str()), Some("Base64Encoder"));
}

#[test]
fn battery_semantic_and_kdoc() {
    let (tfidf, _) = build_corpus_index();
    // Signature/name match on a real Okio-style method. writeUtf8 must be in
    // the top 3 — readUtf8 can match via its glued class-header doc.
    let r = corpus_query(&tfidf, "writeUtf8", 3);
    assert!(
        r.iter().any(|x| x.name == "writeUtf8"),
        "writeUtf8 must rank high: {r:?}"
    );
    // KDoc prose finds the class (documentation tokens are indexed).
    let r = corpus_query(&tfidf, "buffered source", 5);
    assert!(
        r.iter().any(|x| x.name == "Buffer"),
        "KDoc prose must find Buffer: {r:?}"
    );
    // Same-name method: writeUtf8 must be in the top 3 (readUtf8 can match
    // via its glued class-header doc).
    let r = corpus_query(&tfidf, "writeUtf8", 3);
    assert!(
        r.iter().any(|x| x.name == "writeUtf8"),
        "writeUtf8 must rank high: {r:?}"
    );
}

#[test]
fn battery_kind_filter() {
    let (tfidf, _) = build_corpus_index();
    // P2: kind:class narrows to classes; Builder's methods are excluded.
    let r = corpus_query(&tfidf, "kind:class", 20);
    assert!(!r.is_empty());
    assert!(r.iter().all(|x| x.kind == "class"), "got: {:?}", r);
}

#[test]
fn battery_path_and_name_filters() {
    let (tfidf, _) = build_corpus_index();
    // P2: path + name filters compose (case-insensitive).
    let r = corpus_query(&tfidf, "kind:class path:codec", 5);
    assert_eq!(r.first().map(|x| x.name.as_str()), Some("Base64Encoder"));
    let r = corpus_query(&tfidf, "kind:method name:parse", 10);
    assert_eq!(r.len(), 3); // parse x2 + parseFrom (substring match)
    assert!(r.iter().all(|x| x.name.contains("parse")));
}

#[test]
fn battery_generated_downranks_on_tie() {
    let (tfidf, _) = build_corpus_index();
    // P4: same-name Request — real implementation ranks above the protobuf stub.
    // Note: `fun build(): Request` legitimately ranks first on the return-type
    // token — the P4 contract is about same-name ordering, not overall rank.
    let r = corpus_query(&tfidf, "Request", 10);
    let reqs: Vec<_> = r.iter().filter(|x| x.name == "Request").collect();
    assert_eq!(reqs.len(), 2, "both Request classes must match: {r:?}");
    assert!(!reqs[0].generated, "real Request must rank first: {r:?}");
    assert!(reqs[1].generated, "generated stub must rank second: {r:?}");
}

#[test]
fn battery_filters_apply_before_scoring() {
    let (tfidf, _) = build_corpus_index();
    // P2: filters narrow the candidate set; free text scores within it.
    // Both Request classes match "Request", but kind:method excludes classes.
    let r = corpus_query(&tfidf, "kind:method Request", 10);
    assert!(!r.is_empty());
    assert!(r.iter().all(|x| x.kind == "method"));
    // The proto stub's parseFrom is still findable by name+path.
    let r = corpus_query(&tfidf, "kind:method path:proto parseFrom", 5);
    assert_eq!(r.first().map(|x| x.name.as_str()), Some("parseFrom"));
    assert!(r[0].generated);
}

#[test]
fn corpus_symbols_sanity() {
    // Guard the corpus itself: known symbol count so accidental corpus edits
    // (which would silently weaken/strengthen the battery) are noticed.
    let (_, names) = build_corpus_index();
    let classes = names.iter().filter(|(_, k)| k == "class").count();
    let methods = names.iter().filter(|(_, k)| k == "method").count();
    assert_eq!(classes, 8, "corpus class count drifted: {names:?}");
    assert_eq!(methods, 10, "corpus method count drifted: {names:?}");
}
